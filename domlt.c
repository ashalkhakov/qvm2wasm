// NOTE: this acts like set union (no duplicates allowed)
static intlist_t *intlist_insert_sorted(intlist_t *head, int num)
{
    intlist_t *current;

    // end of list?
    if (head == NULL || head->n >= num) { 
        intlist_t *node = (intlist_t *)malloc(sizeof(intlist_t));
        node->n = num;
        node->next = head;
        head = node;
    } else {
        // locate the node before the point of insertion
        current = head;
        while (current->next != NULL && current->next->n < num) {
            current = current->next;
        }
        if (current->n != num) {
            intlist_t *node = (intlist_t *)malloc(sizeof(intlist_t));
            node->n = num;
            node->next = current->next;
            current->next = node;
        }
    }
    return head;
}

void adjdigraph_make(adjdigraph_t *g, int numVerts, int r) {
    assert(numVerts > 0);
    assert(r >= 0 && r < numVerts);

    g->numVerts = numVerts;
    g->r = r;
    g->succ = (intlist_t **)malloc(numVerts * sizeof(intlist_t *));
    memset(g->succ, 0, numVerts * sizeof(intlist_t *));
}

void adjdigraph_insert_edge(adjdigraph_t *g, int v, int w) {
    assert(v >= 0 && v < g->numVerts);
    assert(w >= 0 && w < g->numVerts);

    g->succ[v] = intlist_insert_sorted(g->succ[v], w);
}

void adjdigraph_free(adjdigraph_t *g) {
    for (int i = 0; i < g->numVerts; i++) {
        intlist_t *hd = g->succ[i];
        while (hd != NULL) {
            intlist_t *hd_next = hd->next;
            free(hd);
            // iterate
            hd = hd_next;
        }
    }
    free(g->succ);
    g->r = 0;
    g->numVerts = 0;
    g->succ = NULL;
}


